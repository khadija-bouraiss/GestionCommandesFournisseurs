    private void chargerTable() {
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);
    List<Produit> liste = dao.findAll();
    for (Produit p : liste) {
        model.addRow(new Object[]{
            p.getIdProduit(),
            p.getLibelle(),
            p.getCategorie(),
            p.getPrixAchat(),
            p.getStock()
        });
    }
}

