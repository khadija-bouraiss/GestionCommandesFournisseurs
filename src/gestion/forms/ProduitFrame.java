    private void btnAjouterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAjouterActionPerformed
       // TODO add your handling code here:
        
        String libelle = txtLibelle.getText().trim();
String categorie = txtCategorie.getText().trim();
String prixStr = txtPrixAchat.getText().trim();
String stockStr = txtStock.getText().trim();

if (libelle.isEmpty() || categorie.isEmpty() || prixStr.isEmpty() || stockStr.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this,
        "Veuillez remplir tous les champs !",
        "Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
    return;
}

try {
    double prix = Double.parseDouble(prixStr);
    int stock = Integer.parseInt(stockStr);
    
    if (prix <= 0) {
        javax.swing.JOptionPane.showMessageDialog(this,
            "Le prix doit être supérieur à 0 !",
            "Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }
    if (stock < 0) {
        javax.swing.JOptionPane.showMessageDialog(this,
            "Le stock ne peut pas être négatif !",
            "Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }
    
    Produit p = new Produit(libelle, categorie, prix, stock);
    dao.create(p);
    chargerTable();
    viderChamps();
    javax.swing.JOptionPane.showMessageDialog(this,
        "Produit ajouté avec succès !",
        "Succès", javax.swing.JOptionPane.INFORMATION_MESSAGE);
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
        "Prix et Stock doivent être des nombres !",
        "Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_btnAjouterActionPerformed

    private void btnModifierActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModifierActionPerformed
        // TODO add your handling code here:
        int row = jTable1.getSelectedRow();
if (row == -1) {
    javax.swing.JOptionPane.showMessageDialog(this,
        "Veuillez sélectionner un produit !",
        "Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
    return;
}

String libelle = txtLibelle.getText().trim();
String categorie = txtCategorie.getText().trim();
String prixStr = txtPrixAchat.getText().trim();
String stockStr = txtStock.getText().trim();

if (libelle.isEmpty() || categorie.isEmpty() || prixStr.isEmpty() || stockStr.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this,
        "Veuillez remplir tous les champs !",
        "Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
    return;
}

try {
    double prix = Double.parseDouble(prixStr);
    int stock = Integer.parseInt(stockStr);
    int id = (int) jTable1.getValueAt(row, 0);
    
    Produit p = new Produit(id, libelle, categorie, prix, stock);
    dao.update(p);
    chargerTable();
    viderChamps();
    javax.swing.JOptionPane.showMessageDialog(this,
        "Produit modifié avec succès !",
        "Succès", javax.swing.JOptionPane.INFORMATION_MESSAGE);
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
        "Prix et Stock doivent être des nombres !",
        "Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_btnModifierActionPerformed

    private void btnSupprimerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSupprimerActionPerformed
        // TODO add your handling code here:
        int row = jTable1.getSelectedRow();
if (row == -1) {
    javax.swing.JOptionPane.showMessageDialog(this,
        "Veuillez sélectionner un produit !",
        "Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
    return;
}

String libelle = jTable1.getValueAt(row, 1).toString();
int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
    "Voulez-vous vraiment supprimer " + libelle + " ?",
    "Confirmation", javax.swing.JOptionPane.YES_NO_OPTION);

if (confirm == javax.swing.JOptionPane.YES_OPTION) {
    int id = (int) jTable1.getValueAt(row, 0);
    dao.delete(id);
    chargerTable();
    viderChamps();
    javax.swing.JOptionPane.showMessageDialog(this,
        "Produit supprimé avec succès !",
        "Succès", javax.swing.JOptionPane.INFORMATION_MESSAGE);
}
    }//GEN-LAST:event_btnSupprimerActionPerformed

