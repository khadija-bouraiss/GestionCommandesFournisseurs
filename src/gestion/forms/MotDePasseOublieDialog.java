    private String genererMotDePasse() {
    String chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";
    Random random = new Random();
    StringBuilder sb = new StringBuilder();
    for (int i = 0; i < 8; i++) {
        sb.append(chars.charAt(random.nextInt(chars.length())));
    }
    return sb.toString();
}

private void envoyerEmail(String destinataire, String nouveauMotDePasse) throws Exception {
    String expediteur = "k.bouraiss9327@uca.ac.ma"; // ← mets ton email ici
    String motDePasseEmail = "nmqaxtekwlcbscce"; // ← mot de passe application Gmail

    Properties props = new Properties();
    props.put("mail.smtp.auth", "true");
    props.put("mail.smtp.starttls.enable", "true");
    props.put("mail.smtp.host", "smtp.gmail.com");
    props.put("mail.smtp.port", "587");

    Session session = Session.getInstance(props, new Authenticator() {
        protected PasswordAuthentication getPasswordAuthentication() {
            return new PasswordAuthentication(expediteur, motDePasseEmail);
        }
    });

    Message message = new MimeMessage(session);
    message.setFrom(new InternetAddress(expediteur));
    message.setRecipients(Message.RecipientType.TO, InternetAddress.parse(destinataire));
    message.setSubject("Récupération de mot de passe");
    message.setText("Bonjour,\n\nVotre nouveau mot de passe est : " + nouveauMotDePasse + 
                   "\n\nVeuillez le changer après connexion.\n\nCordialement.");
    Transport.send(message);
}

