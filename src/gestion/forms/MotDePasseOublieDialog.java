    private void btnEnvoyerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEnvoyerActionPerformed
        // TODO add your handling code here:
        
        String email = txtEmail.getText().trim();

if (email.isEmpty()) {
    lblMessage.setForeground(java.awt.Color.RED);
    lblMessage.setText("Veuillez entrer votre email !");
    return;
}

String nouveauMotDePasse = genererMotDePasse();
String hash = PasswordUtil.hasher(nouveauMotDePasse);

boolean updated = dao.updateMotDePasseByEmail(email, hash);

if (!updated) {
    lblMessage.setForeground(java.awt.Color.RED);
    lblMessage.setText("Email introuvable !");
    return;
}

try {
    envoyerEmail(email, nouveauMotDePasse);
    lblMessage.setForeground(java.awt.Color.GREEN);
    lblMessage.setText("Email envoyé avec succès !");
} catch (Exception e) {
    lblMessage.setForeground(java.awt.Color.RED);
    lblMessage.setText("Erreur envoi email !");
    System.out.println("Erreur : " + e.getMessage());
}
    }//GEN-LAST:event_btnEnvoyerActionPerformed

