    private void btnModifierActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModifierActionPerformed
        // TODO add your handling code here:
        int row = jTable1.getSelectedRow();
        if (row == -1) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Veuillez sélectionner une commande !",
                "Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        String statut = jTable1.getValueAt(row, 5).toString();
        if (statut.equals("Livrée")) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Impossible de modifier une commande déjà livrée !",
                "Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        Fournisseur fournisseur = (Fournisseur) cmbFournisseur.getSelectedItem();
        Produit produit = (Produit) cmbProduit.getSelectedItem();
        String quantiteStr = txtQuantite.getText().trim();
        java.util.Date date = dateCommande.getDate();
        String statutNew = cmbStatut.getSelectedItem().toString();

        try {
            int quantite = Integer.parseInt(quantiteStr);
            int id = (int) jTable1.getValueAt(row, 0);
            CommandeAchat c = new CommandeAchat(id, fournisseur, produit, date, quantite, statutNew);
            commandeDAO.update(c);
            chargerTable();
            viderChamps();
            javax.swing.JOptionPane.showMessageDialog(this,
                "Commande modifiée avec succès !",
                "Succès", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "La quantité doit être un nombre !",
                "Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnModifierActionPerformed

    private void btnSupprimerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSupprimerActionPerformed
        // TODO add your handling code here:
        int row = jTable1.getSelectedRow();
        if (row == -1) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Veuillez sélectionner une commande !",
                "Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        String statut = jTable1.getValueAt(row, 5).toString();
        if (statut.equals("Livrée")) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Impossible de supprimer une commande déjà livrée !",
                "Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
            "Voulez-vous vraiment supprimer cette commande ?",
            "Confirmation", javax.swing.JOptionPane.YES_NO_OPTION);

        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            int id = (int) jTable1.getValueAt(row, 0);
            commandeDAO.delete(id);
            chargerTable();
            viderChamps();
            javax.swing.JOptionPane.showMessageDialog(this,
                "Commande supprimée avec succès !",
                "Succès", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_btnSupprimerActionPerformed

