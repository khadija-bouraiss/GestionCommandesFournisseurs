    private void chargerComboFournisseur() {
    cmbFournisseur.removeAllItems();
    List<Fournisseur> liste = fournisseurDAO.findAll();
    for (Fournisseur f : liste) {
        cmbFournisseur.addItem(f);
    }
}

private void chargerComboProduit() {
    cmbProduit.removeAllItems();
    List<Produit> liste = produitDAO.findAll();
    for (Produit p : liste) {
        cmbProduit.addItem(p);
    }
}

private void chargerTable() {
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);
    List<CommandeAchat> liste = commandeDAO.findAll();
    for (CommandeAchat c : liste) {
        model.addRow(new Object[]{
            c.getIdCommande(),
            c.getFournisseur().getNom(),
            c.getProduit().getLibelle(),
            c.getDateCommande(),
            c.getQuantite(),
            c.getStatut()
        });
    }
}

private void viderChamps() {
    cmbFournisseur.setSelectedIndex(0);
    cmbProduit.setSelectedIndex(0);
    dateCommande.setDate(null);
    txtQuantite.setText("");
    cmbStatut.setSelectedIndex(0);
}
    private void btnAjouterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAjouterActionPerformed
        // TODO add your handling code here:
        
        Fournisseur fournisseur = (Fournisseur) cmbFournisseur.getSelectedItem();
Produit produit = (Produit) cmbProduit.getSelectedItem();
String quantiteStr = txtQuantite.getText().trim();
java.util.Date date = dateCommande.getDate();
String statut = cmbStatut.getSelectedItem().toString();

if (fournisseur == null || produit == null || date == null || quantiteStr.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this,
        "Veuillez remplir tous les champs !",
        "Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
    return;
}

try {
    int quantite = Integer.parseInt(quantiteStr);
    if (quantite <= 0) {
        javax.swing.JOptionPane.showMessageDialog(this,
            "La quantité doit être supérieure à 0 !",
            "Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }
    CommandeAchat c = new CommandeAchat(fournisseur, produit, date, quantite, statut);
    commandeDAO.create(c);
    chargerTable();
    viderChamps();
    javax.swing.JOptionPane.showMessageDialog(this,
        "Commande ajoutée avec succès !",
        "Succès", javax.swing.JOptionPane.INFORMATION_MESSAGE);
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
        "La quantité doit être un nombre !",
        "Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_btnAjouterActionPerformed

