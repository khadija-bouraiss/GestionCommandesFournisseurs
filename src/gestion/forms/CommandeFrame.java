            commandeDAO.validerLivraison(id);
            chargerTable();
            javax.swing.JOptionPane.showMessageDialog(this,
                "Livraison validée ! Stock mis à jour !",
                "Succès", javax.swing.JOptionPane.INFORMATION_MESSAGE);
